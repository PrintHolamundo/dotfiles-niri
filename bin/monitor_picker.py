def hypr_get_outputs(env):
    try:
        raw = subprocess.check_output(["hyprctl", "monitors", "all", "-j"], env=env)
        data = json.loads(raw)
    except Exception as e:
        print(f"Error fetching hyprctl monitors: {e}", file=sys.stderr)
        return []

    outputs = []
    order_priority = {"DP-1": 1, "HDMI-A-1": 2, "DP-3": 3}
    sorted_items = sorted(data, key=lambda m: order_priority.get(m.get("name"), 10))

    for item in sorted_items:
        name = item.get("name")
        is_disabled = item.get("disabled", False)
        known = KNOWN_DISPLAYS.get(name, {})
        desc = item.get("description") or item.get("model") or ""

        friendly = known.get("friendly_name")
        if not friendly:
            friendly = f"{desc} ({name})" if desc else name

        icon = known.get("icon", "🖥️")
        hypr_mode = known.get("hypr_mode", "preferred")
        hypr_scale = known.get("hypr_scale", 1.0)
        niri_mode = known.get("niri_mode", "preferred")
        niri_scale = known.get("niri_scale", 1.0)

        outputs.append({
            "name": name,
            "friendly_name": friendly,
            "icon": icon,
            "active": not is_disabled,
            "niri_mode": niri_mode,
            "niri_scale": niri_scale,
            "hypr_mode": hypr_mode,
            "hypr_scale": hypr_scale,
            "width": known.get("width", 1920),
            "height": known.get("height", 1080),
        })
    return outputs

def hypr_migrate_workspaces(target_name, env):
    try:
        raw_wss = subprocess.check_output(["hyprctl", "workspaces", "-j"], env=env)
        wss = json.loads(raw_wss)
        for ws in wss:
            ws_id = ws.get("id")
            if ws_id is not None and ws.get("monitor") != target_name:
                subprocess.run(
                    ["hyprctl", "dispatch", "moveworkspacetomonitor", f"{ws_id} {target_name}"],
                    env=env,
                    check=False
                )
    except Exception as e:
        print(f"Error migrating workspaces in hyprland: {e}", file=sys.stderr)

def hypr_activate_solo(target_name, outputs, env):
    target = next((o for o in outputs if o["name"] == target_name), None)
    if not target:
        return

    # 1. Habilitar objetivo
    cmd_on = f"{target_name},{target['hypr_mode']},0x0,{target['hypr_scale']}"
