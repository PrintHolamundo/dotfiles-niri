# ─────────────────── MAIN LOGIC ───────────────────

def main():
    env = setup_environment()
    comp = detect_compositor(env)

    if comp == "niri":
        outputs = niri_get_outputs(env)
    elif comp == "hyprland":
        outputs = hypr_get_outputs(env)
    else:
        notify("Error", "No se detectó un compositor compatible (Niri o Hyprland).", icon="dialog-error")
        sys.exit(1)

    if not outputs:
        notify("Error", "No se detectaron monitores conectados.", icon="dialog-error")
        sys.exit(1)

    menu_lines = []
    actions = {}

    # 1. Modos "Solo un monitor"
    for o in outputs:
        label = f"{o['icon']}  Solo {o['friendly_name']}"
        menu_lines.append(label)
        actions[label] = ("solo", o["name"])

    # 2. Modo extender todos (si hay 2 o más monitores)
    if len(outputs) > 1:
        label_all = "✨  Extender / Activar todos los monitores"
        menu_lines.append(label_all)
        actions[label_all] = ("all", None)

    # 3. Separador visual
    sep = "──────────────────────────────────────────────"
    menu_lines.append(sep)

    # 4. Toggles individuales para encender o apagar
    for o in outputs:
        if o["active"]:
            label = f"🔴  [ON]  {o['friendly_name']}  ➔  Apagar"
        else:
            label = f"🟢  [OFF] {o['friendly_name']}  ➔  Encender"
        menu_lines.append(label)
        actions[label] = ("toggle", o["name"])

    fuzzel_bin = shutil.which("fuzzel")
    if not fuzzel_bin:
        notify("Error", "Fuzzel no está instalado para mostrar el menú.", icon="dialog-error")
        sys.exit(1)

    fuzzel_cmd = [
        fuzzel_bin,
        "--dmenu",
        "--prompt=📺 Seleccionar Monitor: ",
        f"--lines={min(len(menu_lines), 10)}",
        "--minimal-lines",
        "--width=48",
        "--border-radius=12",
        "--border-width=2",
        "--layer=overlay",
        "--no-sort",
    ]

    colors = get_theme_colors()
    if colors:
        fuzzel_cmd.extend([
            f"--background-color={colors['bg']}",
            f"--text-color={colors['fg']}",
            f"--prompt-color={colors['accent']}",
            f"--input-color={colors['fg']}",
            f"--match-color={colors['match']}",
            f"--selection-color={colors['sel_bg']}",
            f"--selection-text-color={colors['sel_fg']}",
            f"--selection-match-color={colors['sel_fg']}",
            f"--border-color={colors['accent']}",
        ])

    try:
        proc = subprocess.Popen(
            fuzzel_cmd,
            stdin=subprocess.PIPE,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            env=env,
        )
        stdout, _ = proc.communicate(input="\n".join(menu_lines))
    except Exception as e:
        print(f"Error executing fuzzel: {e}", file=sys.stderr)
        sys.exit(1)

    selected = stdout.strip()
    if not selected or selected == sep or selected not in actions:
        sys.exit(0)

    act_type, target = actions[selected]

    if comp == "niri":
        if act_type == "solo":
            niri_activate_solo(target, outputs, env)
        elif act_type == "all":
            niri_activate_all(outputs, env)
        elif act_type == "toggle":
            niri_toggle_output(target, outputs, env)
    elif comp == "hyprland":
        if act_type == "solo":
            hypr_activate_solo(target, outputs, env)
        elif act_type == "all":
            hypr_activate_all(outputs, env)
        elif act_type == "toggle":
            hypr_toggle_output(target, outputs, env)

if __name__ == "__main__":
    main()
