def niri_get_outputs(env):
    try:
        raw = subprocess.check_output(["niri", "msg", "-j", "outputs"], env=env)
        data = json.loads(raw)
    except Exception as e:
        print(f"Error fetching niri outputs: {e}", file=sys.stderr)
        return []

    outputs = []
    order_priority = {"DP-1": 1, "HDMI-A-1": 2, "DP-3": 3}
    sorted_keys = sorted(data.keys(), key=lambda k: order_priority.get(k, 10))

    for name in sorted_keys:
        info = data[name]
        is_active = info.get("logical") is not None
        known = KNOWN_DISPLAYS.get(name, {})
        make = info.get("make") or ""
        model = info.get("model") or ""

        friendly = known.get("friendly_name")
        if not friendly:
            clean_name = f"{make} {model}".strip()
            friendly = f"{clean_name} ({name})" if clean_name else name

        icon = known.get("icon", "🖥️")
        
        niri_mode = known.get("niri_mode")
        niri_scale = known.get("niri_scale", 1.0)
        hypr_mode = known.get("hypr_mode", "preferred")
        hypr_scale = known.get("hypr_scale", 1.0)
        width = known.get("width", 1920)
        height = known.get("height", 1080)

        if not niri_mode and info.get("modes"):
            pref = next((m for m in info["modes"] if m.get("is_preferred")), info["modes"][0])
            w = pref["width"]
            h = pref["height"]
            r = pref["refresh_rate"] / 1000.0
            niri_mode = f"{w}x{h}@{r:.3f}"
            hypr_mode = f"{w}x{h}@{int(round(r))}"
            width = w
            height = h

        outputs.append({
            "name": name,
            "friendly_name": friendly,
            "icon": icon,
            "active": is_active,
            "niri_mode": niri_mode,
            "niri_scale": niri_scale,
            "hypr_mode": hypr_mode,
            "hypr_scale": hypr_scale,
            "width": width,
            "height": height,
        })

    return outputs

def niri_migrate_windows(target_name, env):
    try:
        raw_wins = subprocess.check_output(["niri", "msg", "-j", "windows"], env=env)
        raw_wss = subprocess.check_output(["niri", "msg", "-j", "workspaces"], env=env)
        wins = json.loads(raw_wins)
        wss = json.loads(raw_wss)
        ws_to_output = {w["id"]: w["output"] for w in wss}

        for win in wins:
            wid = win.get("id")
            cur_out = ws_to_output.get(win.get("workspace_id"))
            if cur_out and cur_out != target_name:
                subprocess.run(
                    ["niri", "msg", "action", "move-window-to-monitor", "--id", str(wid), target_name],
                    env=env,
                    check=False
                )
    except Exception as e:
        print(f"Error migrating windows in niri: {e}", file=sys.stderr)

def niri_activate_solo(target_name, outputs, env):
    target = next((o for o in outputs if o["name"] == target_name), None)
    if not target:
        return

    # 1. Encender el monitor deseado en 0 0
    subprocess.run(["niri", "msg", "output", target_name, "on"], env=env, check=False)
    if target["niri_mode"]:
        subprocess.run(["niri", "msg", "output", target_name, "mode", target["niri_mode"]], env=env, check=False)
    if target["niri_scale"]:
        subprocess.run(["niri", "msg", "output", target_name, "scale", str(target["niri_scale"])], env=env, check=False)
    subprocess.run(["niri", "msg", "output", target_name, "position", "set", "0", "0"], env=env, check=False)
    subprocess.run(["niri", "msg", "action", "focus-monitor", target_name], env=env, check=False)

    # 2. Migrar ventanas de los otros monitores hacia target_name
    niri_migrate_windows(target_name, env)

    # 3. Enfocar el monitor objetivo
    subprocess.run(["niri", "msg", "action", "focus-monitor", target_name], env=env, check=False)

    # 4. Apagar los demás monitores
    for o in outputs:
        if o["name"] != target_name:
            subprocess.run(["niri", "msg", "output", o["name"], "off"], env=env, check=False)

    # 5. Persistir configuración
    save_state = []
    for o in outputs:
        is_target = (o["name"] == target_name)
        save_state.append({
            "name": o["name"],
            "enabled": is_target,
            "niri_mode": o["niri_mode"],
            "niri_scale": o["niri_scale"],
            "hypr_mode": o["hypr_mode"],
            "hypr_scale": o["hypr_scale"],
            "pos_x": 0,
            "pos_y": 0,
        })
    save_persistent_state(save_state, env, "niri")

    notify("Pantalla Activa", f"{target['icon']} Solo {target['friendly_name']}")

def niri_activate_all(outputs, env):
    current_x = 0
    save_state = []

    # Priorizar DP-1 a la izquierda si existe
    has_dp1 = any(o["name"] == "DP-1" for o in outputs)
    ordered = sorted(outputs, key=lambda o: 0 if o["name"] == "DP-1" else 1)

    for o in ordered:
        subprocess.run(["niri", "msg", "output", o["name"], "on"], env=env, check=False)
        if o["niri_mode"]:
            subprocess.run(["niri", "msg", "output", o["name"], "mode", o["niri_mode"]], env=env, check=False)
        if o["niri_scale"]:
            subprocess.run(["niri", "msg", "output", o["name"], "scale", str(o["niri_scale"])], env=env, check=False)
        subprocess.run(["niri", "msg", "output", o["name"], "position", "set", str(current_x), "0"], env=env, check=False)

        save_state.append({
            "name": o["name"],
            "enabled": True,
            "niri_mode": o["niri_mode"],
            "niri_scale": o["niri_scale"],
            "hypr_mode": o["hypr_mode"],
            "hypr_scale": o["hypr_scale"],
            "pos_x": current_x,
            "pos_y": 0,
        })

        logical_w = int(round(o["width"] / o["niri_scale"]))
        current_x += logical_w

    if has_dp1:
        subprocess.run(["niri", "msg", "action", "focus-monitor", "DP-1"], env=env, check=False)

    save_persistent_state(save_state, env, "niri")
    notify("Monitores", "✨ Todos los monitores activados (Extender)")

def niri_toggle_output(target_name, outputs, env):
    target = next((o for o in outputs if o["name"] == target_name), None)
    if not target:
        return

    active_outputs = [o for o in outputs if o["active"]]
    save_state = []

    if target["active"]:
        # Apagar
        if len(active_outputs) <= 1:
            notify("Aviso", f"⚠️ No puedes apagar {target['friendly_name']} porque es el único monitor activo.", icon="dialog-warning")
            return
        other = next(o for o in active_outputs if o["name"] != target_name)
        niri_migrate_windows(other["name"], env)
        subprocess.run(["niri", "msg", "action", "focus-monitor", other["name"]], env=env, check=False)
        subprocess.run(["niri", "msg", "output", target_name, "off"], env=env, check=False)

        for o in outputs:
            is_enabled = (o["name"] != target_name and o["active"])
            save_state.append({
                "name": o["name"],
                "enabled": is_enabled,
                "niri_mode": o["niri_mode"],
                "niri_scale": o["niri_scale"],
                "hypr_mode": o["hypr_mode"],
                "hypr_scale": o["hypr_scale"],
                "pos_x": 0,
                "pos_y": 0,
            })
        notify("Monitor Apagado", f"🔌 {target['friendly_name']} apagado")
    else:
        # Encender
        subprocess.run(["niri", "msg", "output", target_name, "on"], env=env, check=False)
        if target["niri_mode"]:
            subprocess.run(["niri", "msg", "output", target_name, "mode", target["niri_mode"]], env=env, check=False)
        if target["niri_scale"]:
            subprocess.run(["niri", "msg", "output", target_name, "scale", str(target["niri_scale"])], env=env, check=False)
        subprocess.run(["niri", "msg", "output", target_name, "position", "auto"], env=env, check=False)
        subprocess.run(["niri", "msg", "action", "focus-monitor", target_name], env=env, check=False)

        for o in outputs:
            is_enabled = (o["name"] == target_name or o["active"])
            save_state.append({
                "name": o["name"],
                "enabled": is_enabled,
                "niri_mode": o["niri_mode"],
                "niri_scale": o["niri_scale"],
                "hypr_mode": o["hypr_mode"],
                "hypr_scale": o["hypr_scale"],
                "pos_x": 0,
                "pos_y": 0,
            })
        notify("Monitor Encendido", f"🔌 {target['friendly_name']} encendido")

    save_persistent_state(save_state, env, "niri")

