def setup_environment():
    env = os.environ.copy()
    xdg_runtime = env.get("XDG_RUNTIME_DIR", f"/run/user/{os.getuid()}")
    env["XDG_RUNTIME_DIR"] = xdg_runtime

    # Socket de Niri
    if "NIRI_SOCKET" not in env:
        socks = glob.glob(os.path.join(xdg_runtime, "niri.*.sock"))
        if socks:
            socks.sort(key=lambda s: os.path.getmtime(s), reverse=True)
            env["NIRI_SOCKET"] = socks[0]

    # Socket de Wayland
    if "WAYLAND_DISPLAY" not in env:
        wl_sockets = [
            s for s in glob.glob(os.path.join(xdg_runtime, "wayland-*"))
            if not s.endswith(".lock")
        ]
        if wl_sockets:
            wl_sockets.sort(key=lambda s: os.path.getmtime(s), reverse=True)
            env["WAYLAND_DISPLAY"] = os.path.basename(wl_sockets[0])

    # Socket de Hyprland
    if "HYPRLAND_INSTANCE_SIGNATURE" not in env:
        hypr_socks = glob.glob(os.path.join(xdg_runtime, "hypr", "*", ".socket.sock"))
        if hypr_socks:
            hypr_socks.sort(key=lambda s: os.path.getmtime(s), reverse=True)
            env["HYPRLAND_INSTANCE_SIGNATURE"] = os.path.basename(os.path.dirname(hypr_socks[0]))

    return env

def detect_compositor(env):
    if env.get("NIRI_SOCKET") or is_process_running("niri"):
        return "niri"
    if env.get("HYPRLAND_INSTANCE_SIGNATURE") or is_process_running("Hyprland"):
        return "hyprland"
    if is_process_running("kwin_wayland"):
        return "kde"
    return "unknown"

def is_process_running(proc_name):
    try:
        res = subprocess.run(["pgrep", "-x", proc_name], stdout=subprocess.PIPE, stderr=subprocess.PIPE)
        return res.returncode == 0
    except Exception:
        return False

def notify(title, message, icon="video-display"):
    try:
        subprocess.run(["notify-send", "-a", "Selector de Monitores", "-i", icon, title, message], check=False)
    except Exception:
        pass

def get_theme_colors():
    colors_file = os.path.expanduser("~/.cache/ryoku/colors.json")
    if not os.path.exists(colors_file):
        return None
    try:
        with open(colors_file, "r") as f:
            c = json.load(f)
        def to_hex8(val, default):
            if not val:
                return default
            val = val.lstrip("#")
            return val + "ff" if len(val) == 6 else val

        return {
            "bg": to_hex8(c.get("background"), "232a2eff"),
            "fg": to_hex8(c.get("foreground"), "d3c6aaff"),
            "accent": to_hex8(c.get("color4"), "7fbbb3ff"),
            "sel_bg": to_hex8(c.get("color4"), "7fbbb3ff"),
            "sel_fg": to_hex8(c.get("background"), "232a2eff"),
            "match": to_hex8(c.get("color2"), "a7c080ff"),
        }
    except Exception:
        return None

# ─────────────────── PERSISTENCIA ───────────────────

def save_persistent_state(outputs_state, env, comp):
    """
    Guarda la configuración actual de forma persistente en:
    1. ~/.config/niri/cfg/display.kdl (persistencia nativa de Niri)
    2. ~/.config/hypr/monitors_user.lua (persistencia nativa de Hyprland)
    3. ~/.config/last_monitor_layout.json (registro general)
    """
    # 1. Guardar Niri display.kdl
    niri_path = os.path.expanduser("~/.config/niri/cfg/display.kdl")
    niri_lines = [
        "// ────────────── Output Configuration ──────────────\n",
        "// Generated by monitor_picker.py (persistent layout)\n\n"
    ]
    for out in outputs_state:
        name = out["name"]
        if not out.get("enabled", False):
            niri_lines.append(f'output "{name}" {{\n    off\n}}\n\n')
        else:
            niri_lines.append(f'output "{name}" {{\n')
            if out.get("niri_mode"):
                niri_lines.append(f'    mode "{out["niri_mode"]}"\n')
            if out.get("niri_scale"):
                niri_lines.append(f'    scale {out["niri_scale"]}\n')
            if "pos_x" in out and "pos_y" in out:
                niri_lines.append(f'    position x={out["pos_x"]} y={out["pos_y"]}\n')
            niri_lines.append("}\n\n")

    try:
        os.makedirs(os.path.dirname(niri_path), exist_ok=True)
        with open(niri_path, "w") as f:
            f.writelines(niri_lines)
    except Exception as e:
        print(f"Error saving {niri_path}: {e}", file=sys.stderr)

    # 2. Guardar Hyprland monitors_user.lua
    hypr_path = os.path.expanduser("~/.config/hypr/monitors_user.lua")
    hypr_lines = [
        "-- Generated by monitor_picker.py (persistent layout)\n"
    ]
    for out in outputs_state:
        name = out["name"]
        if not out.get("enabled", False):
            hypr_lines.append(f'hl.monitor({{ output = "{name}", disabled = true }})\n')
        else:
            pos_str = f"{out.get('pos_x', 0)}x{out.get('pos_y', 0)}"
            hypr_lines.append(
                f'hl.monitor({{ output = "{name}", mode = "{out.get("hypr_mode", "preferred")}", position = "{pos_str}", scale = {out.get("hypr_scale", 1.0)}, disabled = false }})\n'
            )

    try:
        os.makedirs(os.path.dirname(hypr_path), exist_ok=True)
        with open(hypr_path, "w") as f:
            f.writelines(hypr_lines)
    except Exception as e:
        print(f"Error saving {hypr_path}: {e}", file=sys.stderr)

    # 3. Guardar JSON general
    json_path = os.path.expanduser("~/.config/last_monitor_layout.json")
    try:
        with open(json_path, "w") as f:
            json.dump({
                "timestamp": datetime.now().isoformat(),
                "outputs": outputs_state,
            }, f, indent=2)
    except Exception as e:
        print(f"Error saving {json_path}: {e}", file=sys.stderr)

    # 4. Recargar compositor activo para sincronizar
    if comp == "niri":
        subprocess.run(["niri", "msg", "action", "load-config-file"], env=env, check=False)
    elif comp == "hyprland":
        subprocess.run(["hyprctl", "reload"], env=env, check=False)


